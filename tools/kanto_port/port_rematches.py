#!/usr/bin/env python3
"""Port the VS SEEKER's rematches of the Kanto trainers from pret/pokefirered.

    python3 tools/kanto_port/port_rematches.py --frlg ../pokefirered

Run from the pokeemerald root, after port_trainers.py and port_npcs.py. It

- ports the parties FRLG's trainers have in their rematches (TRAINER_YOUNGSTER_BEN_2 and so on) as
  TRAINER_KANTO_*, numbered from KANTO_REMATCH_TRAINERS_START, with their own trainer flags
  (KANTO_REMATCH_FLAGS_START, see GetTrainerFlagId);
- writes FRLG's rematch table (sRematches in its src/vs_seeker.c) for src/vs_seeker.c;
- puts the trainerbattle_rematch lines the trainer scripts lost back into their *Rematch scripts,
  with the texts they use.

It can be run again: what it already put in the map scripts is left alone.
"""
import argparse, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from port_kanto import read, write
from port_trainers import c_entries, kanto_trainer

GENERATED = "// Generated by tools/kanto_port/port_rematches.py from pokefirered. Do not edit by hand.\n"
OPPONENTS_H = "include/constants/opponents_kanto_rematches.h"
PARTIES = "src/data/kanto_rematch_trainer_parties.h"
ENTRIES = "src/data/kanto_rematch_trainers.h"
TABLE = "src/data/vs_seeker_rematches.h"
OBJECT_EVENTS = "src/data/object_events/kanto_object_events.h"
REMATCH_FLAGS_COUNT = 160  # KANTO_REMATCH_FLAGS_COUNT in include/constants/flags.h
MAX_REMATCH_PARTIES = 6

# FRLG's GetRunningBehaviorFromGraphicsId: how a trainer who wants a rematch shows it
JUMPERS = ["LITTLE_GIRL", "YOUNGSTER", "BOY", "BUG_CATCHER", "LASS", "WOMAN_1", "CRUSH_GIRL", "MAN", "ROCKER",
           "WOMAN_2", "BEAUTY", "BALDING_MAN", "TUBER_F", "CAMPER", "PICNICKER", "COOLTRAINER_M", "COOLTRAINER_F",
           "SWIMMER_M_LAND", "SWIMMER_F_LAND", "BLACK_BELT", "HIKER", "SAILOR"]
SWIMMERS = ["TUBER_M_WATER", "SWIMMER_M_WATER", "SWIMMER_F_WATER"]


def rematch_table(frlg):
    src = read(f"{frlg}/src/vs_seeker.c")
    body = src[src.index("sRematches[] = {") + len("sRematches[] = {"):]
    body = body[:body.index("\n};")]
    rows = []
    for ids in re.findall(r"\{\s*\{([^{}]*)\}", body):
        rows.append([x.strip() for x in ids.split(",") if x.strip()])
    return rows


def label_body(text, label):
    """Lines of a label's body (up to the next blank line or label)."""
    m = re.search(rf"^{re.escape(label)}::?\n(.*?)(?=^\S|^\s*$|\Z)", text, re.S | re.M)
    return m.group(1) if m else None


def raise_hand_graphics():
    """OBJ_EVENT_GFX_KANTO_* whose pics have FRLG's raise-hand frame (frame 9)."""
    t = read(OBJECT_EVENTS)
    frames = {m.group(1): len(re.findall(r"overworld_frame", m.group(2)))
              for m in re.finditer(r"sPicTable_(\w+)\[\] = \{(.*?)\};", t, re.S)}
    out = []
    for m in re.finditer(r"\[(OBJ_EVENT_GFX_KANTO_\w+) - OBJ_EVENT_GFX_KANTO_START\] = &gObjectEventGraphicsInfo_(\w+),", t):
        info = re.search(rf"gObjectEventGraphicsInfo_{m.group(2)} = \{{(.*?)\}};", t, re.S)
        if not info:
            continue
        anims = re.search(r"\.anims = (\w+)", info.group(1)).group(1)
        pics = re.search(r"\.images = sPicTable_(\w+)", info.group(1)).group(1)
        if anims == "sAnimTable_Standard" and frames.get(pics, 0) >= 10:
            out.append(m.group(1))
    return out


def main():
    if not os.path.exists("include/constants/opponents.h"):
        sys.exit("run from the pokeemerald root")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--frlg", default="../pokefirered")
    frlg = ap.parse_args().frlg

    em_opponents = read("include/constants/opponents_kanto.h")
    start = int(re.search(r"#define TRAINER_TOURNAMENT_STORY_LEON\s+(\d+)", em_opponents).group(1)) + 1
    rows = rematch_table(frlg)

    # The trainers of the rematches, in the order of the table
    new = []
    for ids in rows:
        if kanto_trainer(ids[0]) not in em_opponents:
            sys.exit(f"{ids[0]} isn't a Kanto trainer of the maps: run port_trainers.py first")
        for t in ids[1:]:
            if t != "SKIP" and t != ids[0] and t not in new:
                new.append(t)
    if len(new) > REMATCH_FLAGS_COUNT:
        sys.exit("too many rematch trainers for KANTO_REMATCH_FLAGS_COUNT")

    ftrainers = c_entries(read(f"{frlg}/src/data/trainers.h"), "gTrainers")
    fparties = read(f"{frlg}/src/data/trainer_parties.h")
    em_pics = set(re.findall(r"#define (TRAINER_PIC_KANTO_\w+)", read("include/constants/trainers_kanto.h")))
    em_classes = set(re.findall(r"#define (TRAINER_CLASS_\w+)", read("include/constants/trainers.h") + read("include/constants/trainers_kanto.h")))

    consts, entries, parties, done = [], [], [], set()
    for i, t in enumerate(new):
        k = kanto_trainer(t)
        consts.append(f"#define {k:<48} {start + i}")
        body = ftrainers[t]
        cls = re.search(r"\.trainerClass = (\w+)", body).group(1)
        if cls not in em_classes:
            sys.exit(f"{t}: no trainer class {cls}")
        pic = re.search(r"\.trainerPic = (\w+)", body).group(1)
        kpic = "TRAINER_PIC_KANTO_" + pic[len("TRAINER_PIC_"):]
        if kpic not in em_pics:
            sys.exit(f"{t}: no trainer pic {kpic}")
        body = body.replace(f".trainerPic = {pic}", f".trainerPic = {kpic}")
        for party in re.findall(r"\((sParty_\w+)\)", body):
            body = body.replace(party, party.replace("sParty_", "sParty_Kanto"))
            if party not in done:
                done.add(party)
                m = re.search(rf"static const struct (\w+) {party}\[\] = \{{.*?\n\}};", fparties, re.S)
                parties.append(m.group(0).replace(party, party.replace("sParty_", "sParty_Kanto")))
        entries.append(f"    [{k}] = {body},\n")

    write(OPPONENTS_H, GENERATED + "#ifndef GUARD_CONSTANTS_OPPONENTS_KANTO_REMATCHES_H\n#define GUARD_CONSTANTS_OPPONENTS_KANTO_REMATCHES_H\n\n"
          "// The parties of the Kanto trainers' rematches (the VS SEEKER's, see src/vs_seeker.c). They come\n"
          "// after the other Kanto trainers; their trainer flags start at KANTO_REMATCH_FLAGS_START (see\n"
          "// GetTrainerFlagId).\n"
          f"#define KANTO_REMATCH_TRAINERS_START {start}\n\n" + "\n".join(consts) +
          f"\n\n#define NUM_KANTO_REMATCH_TRAINERS {len(new)}\n\n#endif // GUARD_CONSTANTS_OPPONENTS_KANTO_REMATCHES_H\n")
    write(PARTIES, GENERATED + "// Included by data.c after kanto_trainer_parties.h\n\n" + "\n\n".join(parties) + "\n")
    write(ENTRIES, GENERATED + "// Included in gTrainers (src/data/trainers.h)\n\n" + "\n".join(entries))

    # The rematch table, and how the trainers ask for their rematches
    lines = []
    for ids in rows:
        cells = ["SKIP" if t == "SKIP" else kanto_trainer(t) for t in ids]
        lines.append("    {{" + ", ".join(cells) + "}},")
    gfx = set(raise_hand_graphics())
    def cases(names):
        return "\n".join(f"    case OBJ_EVENT_GFX_KANTO_{n}:" for n in names if f"OBJ_EVENT_GFX_KANTO_{n}" in gfx)
    others = sorted(gfx - {f"OBJ_EVENT_GFX_KANTO_{n}" for n in JUMPERS + SWIMMERS})
    write(TABLE, GENERATED + "// Included by src/vs_seeker.c\n\n"
          "// Each row is a trainer's first party and then the parties of its rematches (up to\n"
          f"// MAX_REMATCH_PARTIES = {MAX_REMATCH_PARTIES}). The VS SEEKER offers the parties one after the other as the\n"
          "// story goes on (see TryGetRematchTrainerIdGivenGameState); SKIP leaves one stage out.\n"
          "static const struct RematchData sRematches[] = {\n" + "\n".join(lines) + "\n};\n\n"
          "// How a trainer who wants a rematch shows it. Only the Kanto pics with FRLG's raise-hand frame\n"
          "// can raise a hand: the others just turn to the player's side of the screen.\n"
          "static u8 GetRunningBehaviorFromGraphicsId(u16 graphicsId)\n{\n    switch (graphicsId)\n    {\n"
          + cases(JUMPERS) + "\n        return MOVEMENT_TYPE_RAISE_HAND_AND_JUMP;\n"
          + cases(SWIMMERS) + "\n        return MOVEMENT_TYPE_RAISE_HAND_AND_SWIM;\n"
          + "\n".join(f"    case {g}:" for g in others) + "\n        return MOVEMENT_TYPE_RAISE_HAND_AND_STOP;\n"
          "    default:\n        return MOVEMENT_TYPE_FACE_DOWN;\n    }\n}\n")

    # The trainer scripts
    fscripts = read(f"{frlg}/data/scripts/trainers.inc")
    ftexts = read(f"{frlg}/data/text/trainers.inc")
    from port_npcs import fix_text
    maps = {}
    for root, _, names in os.walk("data/maps"):
        if "scripts.inc" in names:
            maps[os.path.join(root, "scripts.inc")] = None
    em_text = {p: read(p) for p in maps}
    all_text = "\n".join(em_text.values())
    defined = set(re.findall(r"^(\w+):", all_text, re.M))
    added_scripts = added_texts = 0
    for label in re.findall(r"^(\w+_EventScript_\w*Rematch)::", fscripts, re.M):
        battle = re.search(r"^\s*(trainerbattle_rematch(?:_double)? .*)$", label_body(fscripts, label), re.M)
        if not battle:
            continue
        path = next((p for p, t in em_text.items() if re.search(rf"^{label}::$", t, re.M)), None)
        if path is None:
            print(f"warning: no {label} in the maps")
            continue
        text = em_text[path]
        cmd, rest = battle.group(1).split(" ", 1)
        args = [a.strip() for a in rest.split(",")]
        args[0] = kanto_trainer(args[0])
        m = re.search(rf"^{label}::\n", text, re.M)
        after = text[m.end():]
        if not after.lstrip("\t").startswith("trainerbattle_rematch"):
            text = text[:m.end()] + f"\t{cmd} {', '.join(args)}\n" + after
            added_scripts += 1
        new_texts = []
        for t in args[1:]:
            if t in defined:
                continue
            body = label_body(ftexts, t)
            if body is None:
                sys.exit(f"{label}: no text {t} in FRLG")
            new_texts.append(f"{t}:\n" + fix_text(body).rstrip() + "\n")
            defined.add(t)
        if new_texts:
            text = text.rstrip("\n") + "\n\n" + "\n".join(new_texts)
            added_texts += len(new_texts)
        em_text[path] = text
    for p, t in em_text.items():
        if t != read(p):
            write(p, t)
    print(f"ported {len(new)} rematch trainers, {len(rows)} rematch table rows; "
          f"{added_scripts} rematch scripts and {added_texts} texts put back")


if __name__ == "__main__":
    main()
