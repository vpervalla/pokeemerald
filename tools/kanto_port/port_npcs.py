# Objects

KANTO_SCRIPTS = "data/scripts/kanto_npcs.inc"
NPC_BEGIN = "@ BEGIN KANTO NPCS: generated by tools/kanto_port/port_npcs.py from pokefirered. Do not edit by hand."
NPC_END = "@ END KANTO NPCS"
FLAGS_H = "include/constants/flags.h"
# FRLG scripts Emerald has under the same name and that work the same way
SHARED_SCRIPTS = {"EventScript_RockSmash", "EventScript_StrengthBoulder", "EventScript_CutTree",
                  "Common_EventScript_UnionRoomAttendant", "Common_EventScript_WirelessClubAttendant",
                  "Common_EventScript_DirectCornerAttendant", "CableClub_EventScript_MysteryGiftMan"}
MOVEMENT_TYPES = {"MOVEMENT_TYPE_WANDER_AROUND_SLOWER": "MOVEMENT_TYPE_WANDER_AROUND"}
TEXT_FIXES = [(r"\{FONT_(MALE|FEMALE|NORMAL)\}", ""), (r"\{LEFT_PAREN\}", "("), (r"\{RIGHT_PAREN\}", ")")]


def frlg_labels(frlg):
    """label -> body for every label in FRLG's script and text files."""
    files = [f"{frlg}/data/event_scripts.s"]
    for d in ("data/scripts", "data/text", "data/maps"):
        for root, _, names in os.walk(f"{frlg}/{d}"):
            files += [os.path.join(root, n) for n in names if n.endswith(".inc")]
    labels = {}
    for f in files:
        text = read(f)
        for m in re.finditer(r"^(\w+)::?[ \t]*\n(.*?)(?=^\w+::?[ \t]*$|^\s*\.include|\Z)", text, re.S | re.M):
            labels.setdefault(m.group(1), m.group(2))
    return labels


def emerald_labels():
    out = set()
    for root, _, names in os.walk("data"):
        for n in names:
            if n.endswith((".inc", ".s")):
                out |= set(re.findall(r"^(\w+)::", read(os.path.join(root, n)), re.M))
    return out


def allocate_flags(names):
    """Define the FRLG flags Emerald lacks in place of unused (non-daily) Emerald flags."""
    text = read(FLAGS_H)
    defined = set(re.findall(r"#define (FLAG_\w+)", text))
    missing = [n for n in sorted(names) if n not in defined]
    free = [m for m in re.finditer(r"^#define (FLAG_UNUSED_0x([0-9A-F]+))(\s+)(.*?)[ \t]*// Unused Flag[ \t]*$", text, re.M)
            if int(m.group(2), 16) < 0x91F]
    if len(missing) > len(free):
        sys.exit(f"{len(missing)} flags needed but only {len(free)} unused flags are left")
    for name, m in zip(missing, free):
        width = len(m.group(1)) + len(m.group(3))
        text = text.replace(m.group(0), f"#define {name:<{max(width - 1, len(name))}} {m.group(4)} // Kanto (FRLG)", 1)
    write(FLAGS_H, text)
    return missing


def fix_text(body):
    for a, b in TEXT_FIXES:
        body = re.sub(a, b, body)
    # {PLAY_BGM}{MUS_X}: use Emerald's RG version of the song, or drop the music change
    songs = set(re.findall(r"^(MUS_\w+)\s*=", read("charmap.txt"), re.M))
    def bgm(m):
        rg = m.group(1).replace("MUS_", "MUS_RG_", 1)
        return "{PLAY_BGM}{" + rg + "}" if rg in songs else ("{PLAY_BGM}{" + m.group(1) + "}" if m.group(1) in songs else "")
    return re.sub(r"\{PLAY_BGM(?:\}\{| )(MUS_\w+)\}", bgm, body)


def cmd_objects(args):
    frlg = args.frlg
    man = load_manifest()["maps"]
    labels = frlg_labels(frlg)
    em_labels = emerald_labels()
    kanto_gfx = set(re.findall(r"#define (OBJ_EVENT_GFX_KANTO_\w+)", read(KANTO_CONSTANTS)))
    em_localids = set(re.findall(r"#define (LOCALID_\w+)", read("include/constants/map_event_ids.h"))) if os.path.exists("include/constants/map_event_ids.h") else set()
    ported_localids = set()
    for new in man.values():
        ported_localids |= {o.get("local_id") for o in json.loads(read(f"data/maps/{new}/map.json"))["object_events"] if o.get("local_id")}
    em_localids -= ported_localids  # local ids from an earlier run of this tool are ours
    renamed_maps = {f: n for f, n in man.items() if f != n}

    common_texts, common_blocks, flags = {}, [], set()
    stats = {"talk": 0, "item": 0, "trainer": 0, "nurse": 0, "mart": 0, "shared": 0, "fallback": 0, "silent": 0}

    def rename_label(label):
        for f, n in renamed_maps.items():
            if label.startswith(f + "_"):
                return n + label[len(f):]
        return label

    def map_of(label):
        for f in sorted(man, key=len, reverse=True):
            if label.startswith(f + "_"):
                return f
        return None

    def text_label(label, local_texts, mapname):
        """Copy a FRLG text label (and nothing else) and return the name to use for it."""
        if label not in labels:
            return None
        owner = map_of(label)
        if owner is not None:
            new = rename_label(label)
            if man[owner] == mapname:
                local_texts[new] = labels[label]
            else:
                common_texts["Kanto_" + label] = labels[label]
                new = "Kanto_" + label
            return new
        new = "Kanto_" + label
        common_texts[new] = labels[label]
        return new

    def first_text(label, seen=None):
        """First text a script shows, following gotos and calls."""
        seen = seen or set()
        if label in seen or label not in labels or len(seen) > 8:
            return None
        seen.add(label)
        body = labels[label]
        m = re.search(r"^\s*(?:msgbox|message)\s+(\w+)", body, re.M)
        if m and m.group(1) in labels:
            return m.group(1)
        for target in re.findall(r"^\s*(?:goto|call|goto_if_\w+|call_if_\w+)\s+(?:[\w ,]*,\s*)?(\w+)\s*$", body, re.M):
            t = first_text(target, seen)
            if t:
                return t
        return None

    for fname, new in sorted(man.items()):
        fj = json.loads(read(f"{frlg}/data/maps/{fname}/map.json"))
        ej = json.loads(read(f"data/maps/{new}/map.json"))
        fsrc = read(f"{frlg}/data/maps/{fname}/scripts.inc")
        var_gfx = {}
        for var, gfx in re.findall(r"setvar VAR_OBJ_GFX_ID_(\w+), (OBJ_EVENT_GFX_\w+)", fsrc):
            var_gfx.setdefault(f"OBJ_EVENT_GFX_VAR_{var}", gfx)
        objects, scripts, local_texts, marts = [], [], {}, {}
        for idx, o in enumerate(fj["object_events"]):
            if o.get("type") == "clone":
                continue
            gfx = var_gfx.get(o["graphics_id"], o["graphics_id"])
            kgfx = "OBJ_EVENT_GFX_KANTO_" + gfx[len("OBJ_EVENT_GFX_"):] if gfx.startswith("OBJ_EVENT_GFX_") else None
            movement = MOVEMENT_TYPES.get(o["movement_type"], o["movement_type"])
            if kgfx not in kanto_gfx:
                # Pokémon Journals lying on tables have no graphics in FRLG either
                kgfx, movement = "OBJ_EVENT_GFX_KANTO_ITEM_BALL", "MOVEMENT_TYPE_INVISIBLE"
            obj = {}
            local_id = o.get("local_id")
            if local_id:
                if local_id in em_localids:
                    local_id = "LOCALID_KANTO_" + local_id[len("LOCALID_"):]
                obj["local_id"] = local_id
            flag = o.get("flag", "0")
            if flag not in ("0", ""):
                flags.add(flag)
            obj.update({"graphics_id": kgfx, "x": o["x"], "y": o["y"], "elevation": o["elevation"],
                        "movement_type": movement, "movement_range_x": o["movement_range_x"],
                        "movement_range_y": o["movement_range_y"], "trainer_type": "TRAINER_TYPE_NONE",
                        "trainer_sight_or_berry_tree_id": "0", "script": "0x0", "flag": flag})
            script = o.get("script", "0x0")
            body = labels.get(script, "")
            label = rename_label(script) if map_of(script) else f"{new}_EventScript_Object{idx + 1}"
            lines = None
            if script in SHARED_SCRIPTS:
                obj["script"] = script
                stats["shared"] += 1
            elif re.search(r"^\s*finditem\s", body, re.M):
                lines = ["\t" + l.strip() for l in body.strip().splitlines() if l.strip().startswith("finditem")] + ["\tend"]
                stats["item"] += 1
            elif re.search(r"^\s*call (Common_)?EventScript_PkmnCenterNurse\b", body, re.M):
                lid = local_id or str(len(objects) + 1)
                lines = [f"\tsetvar VAR_0x800B, {lid}", "\tcall Common_EventScript_PkmnCenterNurse",
                         "\twaitmessage", "\twaitbuttonpress", "\trelease", "\tend"]
                stats["nurse"] += 1
            elif re.search(r"^\s*pokemart\s+(\w+)", body, re.M):
                items = re.search(r"^\s*pokemart\s+(\w+)", body, re.M).group(1)
                new_items = rename_label(items) if map_of(items) else f"{new}_Items_{items}"
                marts[new_items] = labels[items]
                lines = ["\tlock", "\tfaceplayer", "\tmessage gText_HowMayIServeYou", "\twaitmessage",
                         f"\tpokemart {new_items}", "\tmsgbox gText_PleaseComeAgain, MSGBOX_DEFAULT", "\trelease", "\tend"]
                stats["mart"] += 1
            elif re.search(r"^\s*trainerbattle", body, re.M):
                m = re.search(r"^\s*trainerbattle\w*\s+\w+,\s*(\w+)", body, re.M)
                t = text_label(m.group(1), local_texts, new) if m else None
                if t:
                    lines = [f"\tmsgbox {t}, MSGBOX_NPC", "\tend"]
                stats["trainer"] += 1
            else:
                body_lines = [l.strip() for l in body.strip().splitlines() if l.strip() and not l.strip().startswith("@")]
                simple = body_lines and all(re.match(r"(lock|lockall|faceplayer|release|releaseall|end|waitmessage|waitbuttonpress|closemessage|msgbox \w+(, MSGBOX_\w+)?)$", l) for l in body_lines)
                if simple:
                    lines = []
                    for l in body_lines:
                        m = re.match(r"msgbox (\w+)(.*)", l)
                        if m:
                            t = text_label(m.group(1), local_texts, new)
                            l = f"msgbox {t}{m.group(2)}" if t else ""
                        if l:
                            lines.append("\t" + l)
                    stats["talk"] += 1
                else:
                    t = first_text(script)
                    t = text_label(t, local_texts, new) if t else None
                    if t:
                        lines = [f"\tmsgbox {t}, MSGBOX_NPC", "\tend"]
                        stats["fallback"] += 1
                    else:
                        stats["silent"] += 1
            if lines:
                obj["script"] = label
                script_text = f"{label}::\n" + "\n".join(lines) + "\n"
                if script_text not in scripts:  # several objects can share a script
                    scripts.append(script_text)
            objects.append(obj)

        ej["object_events"] = objects
        write(f"data/maps/{new}/map.json", json.dumps(ej, indent=2) + "\n")

        block = [NPC_BEGIN, ""] + scripts
        for name, items in marts.items():
            block.append(f"\t.align 2\n{name}:\n" + items.rstrip() + "\n")
        for name, text in sorted(local_texts.items()):
            block.append(f"{name}:\n" + fix_text(text).rstrip() + "\n")
        block.append(NPC_END)
        path = f"data/maps/{new}/scripts.inc"
        cur = read(path)
        if NPC_BEGIN in cur:
            cur = cur[:cur.index(NPC_BEGIN)].rstrip("\n") + cur[cur.index(NPC_END) + len(NPC_END):].rstrip("\n")
        write(path, cur.rstrip("\n") + "\n\n" + "\n".join(block) + "\n")

    # Flags, and the ones a new game starts with (FRLG's EventScript_ResetAllMapFlags)
    allocate_flags(flags)
    reset = labels["EventScript_ResetAllMapFlags"]
