#!/usr/bin/env python3
"""Port the NPCs of the Kanto maps from pret/pokefirered.

    python3 tools/kanto_port/port_npcs.py sprites --frlg ../pokefirered
    python3 tools/kanto_port/port_npcs.py objects --frlg ../pokefirered

Run from the pokeemerald root, after port_kanto.py maps. Both commands are idempotent.

sprites: ports every FRLG object event graphic used by the ported maps as OBJ_EVENT_GFX_KANTO_*
         (graphics ids from 256, see include/constants/event_objects_kanto.h), with FRLG's palettes.
         Generated code goes to src/data/object_events/kanto_object_events.h.
objects: puts the FRLG objects (NPCs, item balls, Cut trees...) on the ported maps and gives them
         scripts, see port_objects() for what is and is not ported.
"""
import argparse, json, os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from port_kanto import read, write, load_manifest

GFX_START = 256
KANTO_CONSTANTS = "include/constants/event_objects_kanto.h"
KANTO_HEADER = "src/data/object_events/kanto_object_events.h"
PIC_DIR = "graphics/object_events/pics/kanto"
PAL_DIR = "graphics/object_events/palettes/kanto"
GENERATED = "// Generated by tools/kanto_port/port_npcs.py from pokefirered. Do not edit by hand.\n"

# FRLG animation tables -> Emerald's (same animations, different names)
ANIMS = {"sAnimTable_Standard": "sAnimTable_Standard", "sAnimTable_Inanimate": "sAnimTable_Inanimate",
         "sAnimTable_Nurse": "sAnimTable_Nurse", "sAnimTable_CutTree": "sAnimTable_CuttableTree",
         "sAnimTable_RockSmashRock": "sAnimTable_BreakableRock", "sAnimTable_HoOh": "sAnimTable_HoOh"}
# FRLG's four NPC palettes go in the same slots as Emerald's NPC_1..4 on Kanto maps
NPC_PALETTES = ["NPC_BLUE", "NPC_PINK", "NPC_GREEN", "NPC_WHITE"]


def camel(name):
    return "".join(p.capitalize() for p in name.lower().split("_"))


def used_frlg_gfx(frlg):
    """FRLG graphics ids used by the objects of the ported maps."""
    used = set()
    for fname in load_manifest()["maps"]:
        j = json.loads(read(f"{frlg}/data/maps/{fname}/map.json"))
        for o in j["object_events"]:
            g = o.get("graphics_id", "0")
            if g.startswith("OBJ_EVENT_GFX_") and not g.startswith("OBJ_EVENT_GFX_VAR_"):
                used.add(g)
        # Objects whose graphics are picked by a var get them from the map's scripts.
        src = read(f"{frlg}/data/maps/{fname}/scripts.inc")
        used |= set(re.findall(r"setvar VAR_OBJ_GFX_ID_\w+, (OBJ_EVENT_GFX_\w+)", src))
    return sorted(used)


def c_blocks(text, kind):
    """name -> body of every `<kind> name... = { ... };` definition in text."""
    out = {}
    for m in re.finditer(kind + r"\s+(\w+)(\[\])?\s*=\s*\{(.*?)\n\};", text, re.S):
        out[m.group(1)] = m.group(3)
    return out


def cmd_sprites(args):
    frlg = args.frlg
    fsrc = f"{frlg}/src/data/object_events"
    infos = c_blocks(read(f"{fsrc}/object_event_graphics_info.h"), r"const struct ObjectEventGraphicsInfo")
    pointers = dict(re.findall(r"\[(OBJ_EVENT_GFX_\w+)\]\s*=\s*&(\w+)", read(f"{fsrc}/object_event_graphics_info_pointers.h")))
    pic_tables = c_blocks(read(f"{fsrc}/object_event_pic_tables.h"), r"static const struct SpriteFrameImage")
    graphics = read(f"{fsrc}/object_event_graphics.h")
    pics = dict(re.findall(r"const u(?:16|32) (gObjectEventPic_\w+)\[\] = INCBIN_U(?:16|32)\(\"(.*?)\.4bpp\"\)", graphics))
    pals = dict(re.findall(r"const u16 (gObjectEventPal_\w+)\[\] = INCBIN_U16\(\"(.*?)\.gbapal\"\)", graphics))
    fevent = read(f"{frlg}/src/event_object_movement.c")
    pal_of_tag = {t: p for p, t in re.findall(r"\{(gObjectEventPal_\w+),\s*(OBJ_EVENT_PAL_TAG_\w+)\}", fevent)}
    sheet_args = dict(re.findall(r"\$\(OBJEVENTGFXDIR\)/(\S+)\.4bpp: %\.4bpp: %\.png\n\t\$\(GFX\) \$< \$@ (.*)",
                                 read(f"{frlg}/spritesheet_rules.mk")))
    subsprites = read(f"{fsrc}/object_event_subsprites.h")
    em_subsprites = set(re.findall(r"SubspriteTable (sOamTables_\w+)\[\]", read("src/data/object_events/object_event_subsprites.h")))
    em_oams = set(re.findall(r"OamData (gObjectEventBaseOam_\w+)", read("src/data/object_events/base_oam.h")))
    foams = c_blocks(read(f"{fsrc}/base_oam.h"), r"const struct OamData")

    used = used_frlg_gfx(frlg)
    consts, pic_lines, table_lines, info_lines, ptr_lines = [], [], [], [], []
    extra_lines, done_pics, done_tables, pal_tags = [], set(), set(), {}
    for t in NPC_PALETTES:  # always ported: Kanto maps load these into the NPC palette slots
        pal_tags[f"OBJ_EVENT_PAL_TAG_{t}"] = None
        pal_tags[f"OBJ_EVENT_PAL_TAG_{t}_REFLECTION"] = None

    def kanto_tag(tag):
        return "OBJ_EVENT_PAL_TAG_KANTO_" + tag[len("OBJ_EVENT_PAL_TAG_"):]

    for i, gfx in enumerate(used):
        kname = "OBJ_EVENT_GFX_KANTO_" + gfx[len("OBJ_EVENT_GFX_"):]
        consts.append(f"#define {kname:<48} {GFX_START + i}")
        info_name = pointers[gfx]
        body = infos[info_name]
        new_info = info_name.replace("gObjectEventGraphicsInfo_", "gObjectEventGraphicsInfo_Kanto")
        table = re.search(r"\.images = (\w+)", body).group(1)
        new_table = table.replace("sPicTable_", "sPicTable_Kanto")
        if table not in done_tables:
            done_tables.add(table)
            frames = pic_tables[table]
            for pic in sorted(set(re.findall(r"gObjectEventPic_\w+", frames))):
                if pic in done_pics:
                    continue
                done_pics.add(pic)
                path = pics[pic]  # e.g. graphics/object_events/pics/people/boy
                rel = path[len("graphics/object_events/pics/"):]
                dst = f"{PIC_DIR}/{rel}.png"
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copyfile(f"{frlg}/{path}.png", dst)
                extra = sheet_args.get(rel, "")
                argstr = f', "{extra}"' if extra else ""
                pic_lines.append(f'const u32 {pic.replace("Pic_", "Pic_Kanto")}[] = INCGFX_U32("{dst}", ".4bpp"{argstr});')
            frames = re.sub(r"gObjectEventPic_(\w+)", r"gObjectEventPic_Kanto\1", frames)
            table_lines.append(f"static const struct SpriteFrameImage {new_table}[] = {{{frames}\n}};\n")
        body = body.replace(f".images = {table}", f".images = {new_table}")
        for tagfield in ("paletteTag", "reflectionPaletteTag"):
            tag = re.search(rf"\.{tagfield} = (\w+)", body).group(1)
            if tag != "OBJ_EVENT_PAL_TAG_NONE":
                pal_tags[tag] = None
                body = body.replace(f".{tagfield} = {tag}", f".{tagfield} = {kanto_tag(tag)}")
        anim = re.search(r"\.anims = (\w+)", body).group(1)
        body = body.replace(f".anims = {anim}", f".anims = {ANIMS.get(anim, 'sAnimTable_Standard')}")
        oam = re.search(r"\.oam = &(\w+)", body).group(1)
        if oam not in em_oams:
            body = body.replace(f"&{oam}", f"&{oam.replace('gObjectEventBaseOam_', 'sKantoObjectEventBaseOam_')}")
            if oam not in done_pics:
                done_pics.add(oam)
                extra_lines.append(f"static const struct OamData {oam.replace('gObjectEventBaseOam_', 'sKantoObjectEventBaseOam_')} = {{{foams[oam]}\n}};\n")
        sub = re.search(r"\.subspriteTables = (\w+)", body).group(1)
        size = sub[len("gObjectEventSpriteOamTables_"):]
        if f"sOamTables_{size}" in em_subsprites:
            body = body.replace(sub, f"sOamTables_{size}")
        elif sub not in done_pics:
            # Copy FRLG's subsprite table and the subsprite lists it uses
            done_pics.add(sub)
            parts = re.findall(rf"(const struct Subsprite (gObjectEventSpriteOamTable_{size}_\d+)\[\] = \{{.*?\n\}};)", subsprites, re.S)
            for text, name in parts:
                extra_lines.append("static " + text.replace(name, name.replace("gObjectEvent", "sKanto")) + "\n")
            tbl = re.search(rf"const struct SubspriteTable {sub}\[\] = \{{.*?\n\}};", subsprites, re.S).group(0)
            tbl = re.sub(r"gObjectEventSpriteOamTable_", "sKantoSpriteOamTable_", tbl).replace(sub, f"sKantoOamTables_{size}")
            extra_lines.append("static " + tbl + "\n")
            body = body.replace(sub, f"sKantoOamTables_{size}")
        else:
            body = body.replace(sub, f"sKantoOamTables_{size}")
        info_lines.append(f"const struct ObjectEventGraphicsInfo {new_info} = {{{body}\n}};\n")
        ptr_lines.append(f"    [{kname} - OBJ_EVENT_GFX_KANTO_START] = &{new_info},")

    pal_lines, pal_defs, pal_table = [], [], []
    for i, tag in enumerate(sorted(pal_tags)):
        pal = pal_of_tag[tag]
        path = pals[pal]
        dst = f"{PAL_DIR}/{os.path.basename(path)}.pal"
        os.makedirs(PAL_DIR, exist_ok=True)
        shutil.copyfile(f"{frlg}/{path}.pal", dst)
        new_pal = pal.replace("gObjectEventPal_", "gObjectEventPal_Kanto")
        if new_pal not in "\n".join(pal_lines):
            pal_lines.append(f'const u16 {new_pal}[] = INCGFX_U16("{dst}", ".gbapal");')
        pal_defs.append(f"#define {kanto_tag(tag):<52} 0x{0x1140 + i:04X}")
        pal_table.append(f"    {{{new_pal}, {kanto_tag(tag)}}}, \\")

    write(KANTO_CONSTANTS, GENERATED + "#ifndef GUARD_CONSTANTS_EVENT_OBJECTS_KANTO_H\n#define GUARD_CONSTANTS_EVENT_OBJECTS_KANTO_H\n\n"
          f"// FRLG object event graphics, used by the Kanto maps. They come after OBJ_EVENT_GFX_VAR_F.\n"
          f"#define OBJ_EVENT_GFX_KANTO_START {GFX_START}\n\n" + "\n".join(consts) +
          f"\n\n#define NUM_KANTO_OBJ_EVENT_GFX {len(used)}\n\n#endif // GUARD_CONSTANTS_EVENT_OBJECTS_KANTO_H\n")
    npc_tags = "\n".join(f"    [PALSLOT_NPC_{n + 1}{r}] = OBJ_EVENT_PAL_TAG_KANTO_{t}{r.replace('_REFLECTION', '_REFLECTION')}," for r in ("", "_REFLECTION") for n, t in enumerate(NPC_PALETTES))
    write(KANTO_HEADER, GENERATED + "// Included by event_object_movement.c.\n\n"
          + "\n".join(pal_defs) + "\n\n"
          + "// Entries for sObjectEventSpritePalettes\n#define KANTO_OBJECT_EVENT_SPRITE_PALETTES \\\n" + "\n".join(pal_table) + "\n\n"
          + "// The NPC palettes loaded on Kanto maps, see InitObjectEventPalettes\n"
          + "#define KANTO_NPC_PALETTE_TAGS \\\n" + " \\\n".join(l.rstrip(",") + "," for l in npc_tags.split("\n")) + "\n\n"
          + "\n".join(pal_lines) + "\n\n" + "\n".join(pic_lines) + "\n\n" + "\n".join(table_lines) + "\n"
          + "\n".join(extra_lines) + "\n" + "\n".join(info_lines) + "\n"
          + "static const struct ObjectEventGraphicsInfo *const sKantoObjectEventGraphicsInfoPointers[NUM_KANTO_OBJ_EVENT_GFX] = {\n"
          + "\n".join(ptr_lines) + "\n};\n")
    print(f"ported {len(used)} object event graphics with {len(pal_tags)} palettes")


