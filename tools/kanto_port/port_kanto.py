#!/usr/bin/env python3
"""Port Kanto data from pret/pokefirered into this pokeemerald tree.

    python3 tools/kanto_port/port_kanto.py tilesets --frlg ../pokefirered
    python3 tools/kanto_port/port_kanto.py maps --frlg ../pokefirered            # every map
    python3 tools/kanto_port/port_kanto.py maps PalletTown Route1 --frlg ../pokefirered

Run from the pokeemerald root. Both commands are idempotent.

tilesets: copies every FRLG tileset to data/tilesets/<kind>/kanto_<name>, converts the
          32-bit FRLG metatile attributes to Emerald's 16-bit format (remapping behaviours),
          and adds them to src/data/tilesets/{graphics,metatiles,headers}.h plus tileset_rules_kanto.mk.
          All ported symbols get a "Kanto" prefix (gTileset_KantoPalletTown) so they
          cannot collide with the Hoenn tilesets.
maps:     ports layouts and maps with their warps and connections into gMapGroup_Kanto* groups.
          Maps and layouts that already exist are left alone unless --force is given, so
          edits made afterwards (by hand or in Porymap) survive a re-run.
          NPCs, triggers and signs are stripped until their scripts are ported. Maps and layouts
          whose name already exists in Emerald get a Kanto prefix (see map_report.txt).
"""
import argparse, json, os, re, shutil, struct, sys
from collections import Counter, defaultdict

ROOT = os.getcwd()
PREFIX_SYM = "Kanto"
PREFIX_DIR = "kanto_"
BLOCK_BEGIN = "// BEGIN KANTO PORT: generated by tools/kanto_port/port_kanto.py from pokefirered. Do not edit by hand."
BLOCK_END = "// END KANTO PORT"

