static const u8 sPlayerName[] = _("TESTER");
static const u8 sRivalName[] = _("BLUE");

void TestSave_SetupLeague(void)
{
    u32 i, j;
    struct Pokemon mon;

    StringCopy(gSaveBlock2Ptr->playerName, sPlayerName);
    StringCopy(gSaveBlock2Ptr->rivalName, sRivalName);
    gSaveBlock2Ptr->playerGender = MALE;
    gSaveBlock2Ptr->playerCostume = PLAYER_COSTUME_FRLG;  // RED

    for (i = 0; i < ARRAY_COUNT(sFlags); i++)
        FlagSet(sFlags[i]);
    for (i = 0; i < ARRAY_COUNT(sClearedFlags); i++)
        FlagClear(sClearedFlags[i]);
    for (i = 0; i < ARRAY_COUNT(sVars); i++)
        VarSet(sVars[i][0], sVars[i][1]);
    for (i = 0; i < ARRAY_COUNT(sGymLeaders); i++)
        SetTrainerFlag(sGymLeaders[i]);
    for (i = 0; i < ARRAY_COUNT(sItems); i++)
        AddBagItem(sItems[i][0], sItems[i][1]);
    SetMoney(&gSaveBlock1Ptr->money, 100000);

    for (i = 0; i < ARRAY_COUNT(sParty); i++)
    {
        u16 natDex = SpeciesToNationalPokedexNum(sParty[i].species);
        u8 metLocation = MAPSEC_PALLET_TOWN;

        CreateMon(&mon, sParty[i].species, sParty[i].level, USE_RANDOM_IVS, FALSE, 0, OT_ID_PLAYER_ID, 0);
        for (j = 0; j < MAX_MON_MOVES; j++)
            SetMonMoveSlot(&mon, sParty[i].moves[j], j);
        SetMonData(&mon, MON_DATA_MET_LOCATION, &metLocation);
        GiveMonToPlayer(&mon);  // the party is full after six: PIKACHU goes to the PC
        GetSetPokedexFlag(natDex, FLAG_SET_SEEN);
        GetSetPokedexFlag(natDex, FLAG_SET_CAUGHT);
    }

    SetLastHealLocationWarp(HEAL_LOCATION_INDIGO_PLATEAU);
    // In front of the POKéMON LEAGUE's door (warp at 11,6).
    SetWarpDestination(MAP_GROUP(MAP_INDIGO_PLATEAU_EXTERIOR), MAP_NUM(MAP_INDIGO_PLATEAU_EXTERIOR), WARP_ID_NONE, 11, 7);
    WarpIntoMap();
}
